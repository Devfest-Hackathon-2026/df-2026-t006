/// 哲学者のプロフィール（Gemini に「本人らしく」話してもらうための資料）。
/// ボス戦のボスと、コメント欄の哲学者の返事で、プロンプトに入れて使う。
///
/// 中身は、教科書・入門書でよく知られている考え・著作・言葉（一般的な日本語訳）。
/// AI が言葉や著作をでっち上げないように、引用してよいのはここにある言葉だけにしている。
class PhilosopherProfile {
  const PhilosopherProfile({
    required this.name,
    required this.era,
    required this.ideas,
    required this.works,
    required this.quotes,
    required this.method,
    required this.voice,
  });

  final String name;

  /// 時代と場所
  final String era;

  /// 中心となる考え
  final List<String> ideas;

  /// 主な著作（本人が書いていない場合は、その説明）
  final String works;

  /// よく知られた言葉（引用してよいのはこれだけ）
  final List<String> quotes;

  /// 議論のしかた（どう考え、どう攻めるか）
  final String method;

  /// 話し方
  final String voice;

  /// プロンプトに入れる文
  String toPrompt() =>
      '''
【$nameの資料】
時代: $era
中心となる考え:
${ideas.map((i) => '- $i').join('\n')}
主な著作: $works
よく知られた言葉（引用する時は、この中から一字一句そのまま）:
${quotes.map((q) => '- 「$q」').join('\n')}
議論のしかた: $method
話し方: $voice''';
}

